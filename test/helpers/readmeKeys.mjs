// The key tables of README.md are generated from the data behind the `?` help screen (src/tui/Help.js), so the two cannot drift.
//   node test/helpers/readmeKeys.mjs          print the tables
//   node test/helpers/readmeKeys.mjs --write  replace the block between the markers in README.md
//   node test/helpers/readmeKeys.mjs --write --file README.zh.md   same for another file (use RD_LANG=zh for the local Chinese copy)
// test/readme.test.js fails when the block in README.md differs from what this prints.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { reviewHelpEntries, inboxHelpEntries } from '../../src/tui/Help.js';
import { t } from '../../src/i18n/index.js';

export const START = '<!-- keys:start (generated by test/helpers/readmeKeys.mjs from the ? help; do not edit by hand) -->';
export const END = '<!-- keys:end -->';

const cell = (text) => String(text).replace(/\|/g, '\\|');

function table(entries, firstTitle) {
  const out = [];
  let open = false;
  const head = (title) => {
    out.push(`**${title}**`, '', `| ${t('help.tableKey')} | ${t('help.tableAction')} |`, '| --- | --- |');
    open = true;
  };
  if (firstTitle) head(firstTitle);
  for (const [key, text] of entries) {
    if (text === null) {
      if (open) out.push('');
      head(key);
    } else {
      out.push(`| \`${cell(key)}\` | ${cell(text)} |`);
    }
  }
  out.push('');
  return out;
}

/** The generated block (markers included). */
export function renderKeyBlock() {
  return [START, '', `#### ${t('help.readmeReview')}`, '', ...table(reviewHelpEntries()), `#### ${t('help.readmeInbox')}`, '', ...table(inboxHelpEntries(), t('help.readmeList')), END].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    const i = process.argv.indexOf('--file');
    const name = i > -1 ? process.argv[i + 1] : 'README.md';
    if (!name) throw new Error('--file needs a file name');
    const file = fileURLToPath(new URL(`../../${name}`, import.meta.url));
    const text = fs.readFileSync(file, 'utf8');
    const a = text.indexOf('<!-- keys:start');
    const b = text.indexOf(END);
    if (a === -1 || b === -1) throw new Error(`${name} has no keys:start / keys:end markers`);
    fs.writeFileSync(file, text.slice(0, a) + renderKeyBlock() + text.slice(b + END.length));
    console.log(`${name} updated`);
  } else {
    console.log(renderKeyBlock());
  }
}
